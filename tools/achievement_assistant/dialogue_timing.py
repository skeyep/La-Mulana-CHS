def complete_dialogue_hints(dialogues, range_text):
    for d in dialogues:
        block = d['block']
        if block in SPECIAL:
            pre, action, deadline, brief = SPECIAL[block]
        elif d['random_windows']:
            spans = d['random_windows']
            pre = '先听完该人物当前优先的剧情对白。'
            if d['person'] == 0:
                pre = '已唤醒穆尔，听完当前优先剧情。'
            action = '在流程点数' + range_text(spans) + '时反复交谈。'
            deadline = '最后窗口到' + str(spans[-1][1]) + '点；错过前段仍可等后段。'
            if d['person'] == 0:
                deadline += '进入终战或交回危险泳装后关闭。'
            brief = d['short_note']  # Dynamic shortTiming renders the actual next window.
        else:
            held = next((r for r in d['rules'] if r[0] == 3), None)
            if held:
                pre = '已取得' + d['title'] + '。'
                action = d['note'] + '若先出现剧情对白，听完再谈。'
                deadline = '无独立点数截止；先展示，再将道具用于机关。'
                brief = d['note']
                if held[1] == 31:
                    deadline = '在女性像变为孕妇像前；长老与穆尔各谈一次。'
                    brief = '装备女性像，长老与穆尔各谈一次；变成孕妇像前补齐。'
                if held[1] == 25:
                    deadline = '时之灯仍有充能时；耗尽后须重新充能再展示。'
                if d['person'] == 0:
                    deadline += '交回危险泳装前。'
            else:
                spans = sorted({(r[1], min(r[2], 255)) for r in d['rules'] if r[0] == 1})
                assert spans, d
                pre = '先听完当前优先剧情；取消装备展示道具。'
                if d['person'] == 0:
                    pre = '已听完穆尔醒来对白；先听完当前优先剧情。'
                action = '流程点数' + range_text(spans) + '时交谈。'
                deadline = '最后窗口到' + str(spans[-1][1]) + '点；加点前先补听。'
                brief = action + ('有多个窗口，前段未听可等后段。' if len(spans) > 1 else '')
                if d['person'] == 0:
                    deadline += '交回危险泳装前。'
                if block in (394, 395):
                    brief = '听完穆尔醒来对白后，' + action + '先补听再加点。'
        d['timing'] = dict(prerequisites=pre, action=action, deadline=deadline)
        d['note'] = '前置：' + pre + '\n操作：' + action + '\n截止：' + deadline
        d['short_note'] = brief
