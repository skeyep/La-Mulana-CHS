"""Export actual NPC doors and ordered selector tables, including the early Mulbruk door."""
import json


def generate(root, parsed, world):
    commands = lambda n: [s['arguments'] for s in parsed['blocks'][n]['segments'] if s.get('opcode') == 78]
    masters = {719, 485, 1082, 1083, 484, 1080, 1081, 1019}
    direct = {912: 392, 990: 393, 1013: 418}
    doors = []
    tables = {}
    for obj in world['objects']:
        args = obj['args']
        if obj['object_type'] != 160 or len(args) < 5:
            continue
        master = args[4]
        if master not in masters | direct.keys():
            continue
        person = 0 if obj['container']['zone_index'] == 3 else 1
        groups = commands(master)[0] if master in masters else []
        if groups:
            assert len(groups) == 4
            for kind, table in enumerate(groups):
                tables[table] = dict(kind=kind, records=commands(table))
        doors.append(dict(person=person, root=master, direct=direct.get(master, -1), groups=groups,
                          tests=[[t['flag_index'], t['value_raw_u8'], t['opcode']] for t in obj['test_operations']],
                          object_id=obj['id'], container=obj['container']))
    data = dict(doors=doors, tables=tables)
    out = root/'localization/achievement-assistant/dialogue-routes.json'
    out.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding='utf-8')
    lines = ['// Generated by dialogue_routes.py from installed JP scripts and RCD.',
             'struct SelectorRow { int a,b,block,mode; };']
    for table, value in sorted(tables.items()):
        records = value['records']
        assert all(len(r) == (2 if value['kind'] == 3 else 4) for r in records)
        # Random rows store their target in block, retaining duplicate weights.
        records = [[0, 0, *r] if value['kind'] == 3 else r for r in records]
        lines.append('static const SelectorRow TABLE_'+str(table)+'[] = {' + ','.join(
            '{'+','.join(map(str, r))+'}' for r in records)+'};')
    lines += ['struct SelectorTable { int id,kind,count; const SelectorRow* rows; };',
              'static const SelectorTable SELECTOR_TABLES[] = {']
    for table, value in sorted(tables.items()):
        lines.append('{'+f'{table},{value["kind"]},{len(value["records"])},TABLE_{table}'+'},')
    lines += ['};', 'struct DialogueDoor { int person,root,direct,groups[4]; Rule tests[8]; };',
              'static const DialogueDoor DIALOGUE_DOORS[] = {']
    for d in doors:
        tests = d['tests'] + [[0, 0, -1]]*(8-len(d['tests']))
        groups = d['groups'] or [0]*4
        lines.append('{'+','.join(map(str, [d['person'],d['root'],d['direct']]))+',{'+','.join(map(str,groups))+'},{'+','.join(
            '{'+','.join(map(str,t))+'}' for t in tests)+'}},')
    lines.append('};')
    (root/'tools/achievement_assistant/routes.generated.h').write_text('\n'.join(lines)+'\n', encoding='utf-8')
    return data
